#!/usr/bin/env node
/**
 * Generates MySQL 8 DDL from prisma/schema.prisma using Prisma's DMMF (WASM, no engine binary needed).
 * Adds what Prisma cannot express, read from triple-slash annotations:
 *   field  `/// generated: <expr>`  -> STORED generated column
 *   field  `/// fk: <table>.<col> <RESTRICT|CASCADE|SET NULL>` -> foreign key without Prisma relation
 *   model  `/// check: <expr>`      -> CHECK constraint
 * Usage: node prisma/tools/generate-ddl.cjs [outFile]
 */
const fs = require('fs');
const path = require('path');
const wasm = require('@prisma/prisma-schema-wasm');

const schemaPath = path.join(__dirname, '..', 'schema.prisma');
const schema = fs.readFileSync(schemaPath, 'utf8');
const dmmf = JSON.parse(wasm.get_dmmf(JSON.stringify({ prismaSchema: [['schema.prisma', schema]] })));
const { models, enums, indexes } = dmmf.datamodel;

const enumMap = Object.fromEntries(enums.map((e) => [e.name, e.values.map((v) => v.dbName || v.name)]));
const modelMap = Object.fromEntries(models.map((m) => [m.name, m]));
const tableOf = (m) => m.dbName || m.name;
const colOf = (f) => f.dbName || f.name;
const q = (s) => '`' + s + '`';

function docLines(doc) {
  return (doc || '').split('\n').map((s) => s.trim()).filter(Boolean);
}

function sqlType(f) {
  if (f.kind === 'enum') return `ENUM(${enumMap[f.type].map((v) => `'${v}'`).join(',')})`;
  const nt = f.nativeType;
  if (nt) {
    const [name, args] = nt;
    const a = args && args.length ? `(${args.join(',')})` : '';
    switch (name) {
      case 'VarChar': return `VARCHAR${a}`;
      case 'Char': return `CHAR${a}`;
      case 'Text': return 'TEXT';
      case 'MediumText': return 'MEDIUMTEXT';
      case 'LongText': return 'LONGTEXT';
      case 'UnsignedBigInt': return 'BIGINT UNSIGNED';
      case 'UnsignedInt': return 'INT UNSIGNED';
      case 'UnsignedSmallInt': return 'SMALLINT UNSIGNED';
      case 'UnsignedTinyInt': return 'TINYINT UNSIGNED';
      case 'TinyInt': return 'TINYINT';
      case 'SmallInt': return 'SMALLINT';
      case 'Int': return 'INT';
      case 'BigInt': return 'BIGINT';
      case 'Decimal': return `DECIMAL${a}`;
      case 'DateTime': return `DATETIME${a}`;
      case 'Date': return 'DATE';
      case 'Time': return `TIME${a}`;
      case 'VarBinary': return `VARBINARY${a}`;
      case 'Binary': return `BINARY${a}`;
      case 'Blob': return 'BLOB';
      default: throw new Error(`Unsupported native type ${name} on ${f.name}`);
    }
  }
  switch (f.type) {
    case 'String': return 'VARCHAR(191)';
    case 'Int': return 'INT';
    case 'BigInt': return 'BIGINT';
    case 'Boolean': return 'BOOLEAN';
    case 'DateTime': return 'DATETIME(3)';
    case 'Decimal': return 'DECIMAL(65,30)';
    case 'Float': return 'DOUBLE';
    case 'Json': return 'JSON';
    case 'Bytes': return 'LONGBLOB';
    default: throw new Error(`Unsupported type ${f.type}`);
  }
}

function sqlDefault(f) {
  if (!f.hasDefaultValue || f.default === undefined) return '';
  const d = f.default;
  if (typeof d === 'object' && d !== null && !Array.isArray(d)) {
    if (d.name === 'autoincrement') return ' AUTO_INCREMENT';
    if (d.name === 'now') return ' DEFAULT CURRENT_TIMESTAMP(3)';
    return '';
  }
  if (f.type === 'Json') return '';
  if (typeof d === 'boolean') return ` DEFAULT ${d ? 1 : 0}`;
  if (typeof d === 'number') return ` DEFAULT ${d}`;
  if (typeof d === 'string') {
    if (f.kind === 'enum') return ` DEFAULT '${d}'`;
    if (f.type === 'Decimal' || f.type === 'Int' || f.type === 'BigInt') return ` DEFAULT ${d}`;
    return ` DEFAULT '${d.replace(/'/g, "''")}'`;
  }
  return '';
}

const short = (s) => (s.length <= 64 ? s : s.slice(0, 55) + '_' + require('crypto').createHash('md5').update(s).digest('hex').slice(0, 8));

const out = [];
const fks = [];
out.push('-- Generated by prisma/tools/generate-ddl.cjs from prisma/schema.prisma. Do not edit by hand.');
out.push('SET NAMES utf8mb4;');
out.push('SET FOREIGN_KEY_CHECKS = 0;');

for (const m of models) {
  const table = tableOf(m);
  const lines = [];
  const pk = [];
  for (const f of m.fields) {
    if (f.kind === 'object') {
      if (f.relationFromFields && f.relationFromFields.length) {
        const target = modelMap[f.type];
        const action = (f.relationOnDelete || (f.isRequired ? 'Restrict' : 'SetNull'))
          .replace('SetNull', 'SET NULL').replace('NoAction', 'NO ACTION').toUpperCase();
        fks.push({
          table,
          cols: f.relationFromFields.map((n) => colOf(m.fields.find((x) => x.name === n))),
          refTable: tableOf(target),
          refCols: f.relationToFields.map((n) => colOf(target.fields.find((x) => x.name === n))),
          action,
        });
      }
      continue;
    }
    const docs = docLines(f.documentation);
    const gen = docs.find((d) => d.startsWith('generated:'));
    const fk = docs.find((d) => d.startsWith('fk:'));
    let line = `  ${q(colOf(f))} ${sqlType(f)}`;
    if (gen) {
      line += ` GENERATED ALWAYS AS (${gen.slice('generated:'.length).trim()}) STORED NULL`;
    } else {
      line += f.isRequired ? ' NOT NULL' : ' NULL';
      if (f.isUpdatedAt) line += ' DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)';
      else line += sqlDefault(f);
    }
    lines.push(line);
    if (f.isId) pk.push(colOf(f));
    if (fk) {
      const m2 = fk.slice(3).trim().match(/^([a-z_0-9]+)\.([a-z_0-9]+)\s+(.+)$/i);
      if (!m2) throw new Error(`Bad fk annotation on ${m.name}.${f.name}: ${fk}`);
      fks.push({ table, cols: [colOf(f)], refTable: m2[1], refCols: [m2[2]], action: m2[3].toUpperCase() });
    }
  }
  if (m.primaryKey) pk.push(...m.primaryKey.fields.map((n) => colOf(m.fields.find((x) => x.name === n))));
  lines.push(`  PRIMARY KEY (${pk.map(q).join(', ')})`);

  for (const idx of indexes.filter((i) => i.model === m.name && i.type !== 'id')) {
    const cols = idx.fields.map((x) => colOf(m.fields.find((f) => f.name === x.name)));
    const suffix = idx.type === 'unique' ? 'key' : idx.type === 'fulltext' ? 'ft' : 'idx';
    const name = short(idx.dbName || `${table}_${cols.join('_')}_${suffix}`);
    const kw = idx.type === 'unique' ? 'UNIQUE INDEX' : idx.type === 'fulltext' ? 'FULLTEXT INDEX' : 'INDEX';
    lines.push(`  ${kw} ${q(name)} (${cols.map(q).join(', ')})`);
  }
  let checkNo = 0;
  for (const d of docLines(m.documentation).filter((x) => x.startsWith('check:'))) {
    checkNo += 1;
    lines.push(`  CONSTRAINT ${q(short(`${table}_chk_${checkNo}`))} CHECK (${d.slice('check:'.length).trim()})`);
  }
  out.push(`\nCREATE TABLE ${q(table)} (\n${lines.join(',\n')}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;`);
}

out.push('\n-- Foreign keys');
const seen = new Set();
for (const fk of fks) {
  let name = short(`${fk.table}_${fk.cols.join('_')}_fkey`);
  while (seen.has(name)) name = short(name + '2');
  seen.add(name);
  out.push(
    `ALTER TABLE ${q(fk.table)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${fk.cols.map(q).join(', ')}) REFERENCES ${q(fk.refTable)} (${fk.refCols.map(q).join(', ')}) ON DELETE ${fk.action} ON UPDATE RESTRICT;`,
  );
}
out.push('\nSET FOREIGN_KEY_CHECKS = 1;\n');

const target = process.argv[2] || path.join(__dirname, '..', 'migrations', '20261106000000_init', 'migration.sql');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out.join('\n'));
console.log(`Wrote ${models.length} tables, ${fks.length} foreign keys -> ${path.relative(process.cwd(), target)}`);
