function createConcreteFloorTexture(): THREE.CanvasTexture {
  const size = 512;
  const c = document.createElement('canvas');
  c.width = size;
  c.height = size;
  const g = c.getContext('2d')!;

  g.fillStyle = '#f3eee4';
  g.fillRect(0, 0, size, size);

  // Subtle warm mineral aggregate clouds
  for (let i = 0; i < 36; i++) {
    const x = ((i * 97) % size);
    const y = ((i * 151) % size);
    const r = 45 + (i % 5) * 20;
    const gr = g.createRadialGradient(x, y, 0, x, y, r);
    gr.addColorStop(0, i % 2 === 0 ? 'rgba(180,164,136,0.06)' : 'rgba(255,252,246,0.09)');
    gr.addColorStop(1, 'rgba(0,0,0,0)');
    g.fillStyle = gr;
    g.fillRect(x - r, y - r, r * 2, r * 2);
  }

  // Crisp architectural tile joints
  g.strokeStyle = 'rgba(14, 27, 44, 0.085)';
  g.lineWidth = 2;
  const step = 128;
  for (let p = 0; p <= size; p += step) {
    g.beginPath();
    g.moveTo(p, 0);
    g.lineTo(p, size);
    g.stroke();
    g.beginPath();
    g.moveTo(0, p);
    g.lineTo(size, p);
    g.stroke();
  }

  // Secondary subtle sub-grid
  g.strokeStyle = 'rgba(176, 128, 42, 0.055)';
  g.lineWidth = 1;
  for (let p = 64; p < size; p += step) {
    g.beginPath();
    g.moveTo(p, 0);
    g.lineTo(p, size);
    g.stroke();
    g.beginPath();
    g.moveTo(0, p);
    g.lineTo(size, p);
    g.stroke();
  }

  const tex = new THREE.CanvasTexture(c);
  tex.colorSpace = THREE.SRGBColorSpace;
  tex.wrapS = THREE.RepeatWrapping;
  tex.wrapT = THREE.RepeatWrapping;
  tex.anisotropy = 8;
  return tex;
}
